#!/usr/bin/env node
/** Smoke: xuất / đối chiếu / sinh lược đồ PostgreSQL từ SQLite (scripts/db-export.js), gồm các giá trị biên. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import Database from 'better-sqlite3';
import { exportDb, verifyDb, pgSchema } from './db-export.js';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'dbx-smoke-'));
const dbp = path.join(tmp, 't.db');
const db = new Database(dbp);
db.pragma('journal_mode = WAL');
db.exec(`
  CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT NOT NULL UNIQUE COLLATE NOCASE, note TEXT, score REAL, blob BLOB, created_at INTEGER DEFAULT (strftime('%s','now')), role TEXT DEFAULT 'operator');
  CREATE TABLE kv (a TEXT NOT NULL, b INTEGER NOT NULL, v TEXT, PRIMARY KEY (a, b));
  CREATE TABLE nopk (x TEXT);
  CREATE INDEX idx_users_role ON users(role);
`);
db.prepare('INSERT INTO users (username, note, score, blob) VALUES (?,?,?,?)').run('an', 'có "nháy" và, dấu phẩy\nvà xuống dòng', 3.5, Buffer.from([0, 1, 255]));
db.prepare('INSERT INTO users (username, note, score, blob) VALUES (?,?,?,?)').run('Bình', '', null, null);
db.prepare('INSERT INTO users (username, note) VALUES (?,?)').run('cuong', null);
db.prepare('INSERT INTO kv VALUES (?,?,?)').run('k', 1, '\\N');       // chuỗi "\N" thật phải khác NULL
db.prepare('INSERT INTO kv VALUES (?,?,?)').run('k', 2, null);
db.prepare('INSERT INTO nopk VALUES (?)').run('😀 unicode');
db.close();

let failed = 0;
const ok = (c, m) => { if (c) console.log('OK', m); else { console.error('FAIL', m); failed += 1; } };

const out = path.join(tmp, 'export');
const m = await exportDb({ dbPath: dbp, outDir: out });
ok(Object.keys(m.tables).join() === 'kv,nopk,users' && m.tables.users.rows === 3 && m.tables.kv.rows === 2, 'xuất đủ 3 bảng, đúng số dòng');
const csv = fs.readFileSync(path.join(out, 'users.csv'), 'utf8');
ok(csv.includes('"có ""nháy"" và, dấu phẩy\nvà xuống dòng"'), 'CSV: nháy kép, dấu phẩy, xuống dòng được thoát đúng');
ok(csv.includes('"\\x0001ff"'), 'CSV: BLOB dạng hex \\x…');
ok(/,\\N,\\N,/.test(csv.split('\n').find((l) => l.includes('"Bình"')) || '') || csv.includes('"Bình","",\\N,\\N'), 'CSV: NULL = \\N, chuỗi rỗng = ""');
const kv = fs.readFileSync(path.join(out, 'kv.csv'), 'utf8');
ok(kv.includes('"k",1,"\\N"') && kv.includes('"k",2,\\N'), 'chuỗi "\\N" thật khác NULL');

const v1 = await verifyDb({ dbPath: dbp, exportDir: out });
ok(v1.ok, 'verify: DB nguyên vẹn → khớp');

// sửa một giá trị rồi verify phải báo khác
const w = new Database(dbp);
w.prepare("UPDATE users SET note = 'đổi' WHERE username = 'cuong'").run();
w.close();
const v2 = await verifyDb({ dbPath: dbp, exportDir: out });
ok(!v2.ok && v2.diffs.some((d) => d.startsWith('users:')), 'verify: sửa một dòng → báo khác ở bảng users');

// thêm dòng → số dòng khác
const w2 = new Database(dbp);
w2.prepare("INSERT INTO nopk VALUES ('thêm')").run();
w2.close();
const v3 = await verifyDb({ dbPath: dbp, exportDir: out });
ok(v3.diffs.some((d) => d.startsWith('nopk: số dòng')), 'verify: thêm dòng → báo số dòng khác');

// file CSV bị sửa sau khi xuất
fs.appendFileSync(path.join(out, 'kv.csv'), '"x",9,"y"\n');
const v4 = await verifyDb({ dbPath: dbp, exportDir: out });
ok(v4.diffs.some((d) => d.includes('kv.csv đã bị thay đổi')), 'verify: CSV bị sửa sau khi xuất bị phát hiện');

pgSchema({ exportDir: out });
const ddl = fs.readFileSync(path.join(out, 'schema.pg.sql'), 'utf8');
const imp = fs.readFileSync(path.join(out, 'import.psql'), 'utf8');
ok(ddl.includes('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY') && ddl.includes('PRIMARY KEY ("id")'), 'pg: khoá chính tự tăng → IDENTITY + PRIMARY KEY');
ok(ddl.includes('PRIMARY KEY ("a", "b")'), 'pg: khoá chính ghép');
ok(ddl.includes('"blob" BYTEA') && ddl.includes('"score" DOUBLE PRECISION'), 'pg: BLOB→BYTEA, REAL→DOUBLE PRECISION');
ok(ddl.includes("DEFAULT 'operator'") && ddl.includes('XEM LẠI: mặc định SQLite'), 'pg: mặc định đơn giản giữ nguyên, hàm SQLite được đánh dấu XEM LẠI');
ok(ddl.includes('CREATE INDEX idx_users_role'), 'pg: chỉ mục được sinh');
ok(!ddl.split('\n').some((l) => l.includes('--') && l.trimEnd().endsWith(',')), 'pg: không có dấu phẩy nằm sau chú thích (SQL hợp lệ)');
ok(imp.includes("\\copy \"users\"") && imp.includes("NULL '\\N'") && imp.includes('setval(pg_get_serial_sequence') && imp.includes('(count(*) = 3)'), 'pg: lệnh \\copy, đặt lại sequence, đối chiếu số dòng');

fs.rmSync(tmp, { recursive: true, force: true });
if (failed) { console.error(`\n${failed} lỗi`); process.exit(1); }
console.log('\nsmoke-db-export OK');
