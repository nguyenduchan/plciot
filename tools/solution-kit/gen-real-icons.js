#!/usr/bin/env node
/**
 * Sinh tools/GatewayApp/Ui/IconReal.g.cs từ webapp/icons-real.js (+ icons-3d*.js làm hình dự phòng):
 * cùng một bản vẽ icon thiết bị THỰC TẾ (3D + phẳng) cho webapp và GatewayApp. Chạy lại mỗi khi sửa icons-real.js:
 *   node tools/solution-kit/gen-real-icons.js
 * Kết quả có SVG của từng thiết bị ở hai dạng + bảng gradient (<defs>); GatewayApp/Ui/RealIcon.cs vẽ bằng GDI+.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const repo = path.resolve(__dirname, '..', '..');
const web = (f) => fs.readFileSync(path.join(repo, 'webapp', f), 'utf8');

// môi trường trình duyệt tối thiểu: các file icons-*.js chỉ cần window + document.body.appendChild(<defs>)
const defs = [];
const sandbox = {
  document: {
    body: { appendChild: (d) => defs.push(d.innerHTML) },
    addEventListener() {},
    getElementById: () => null,
    createElement: () => ({ id: '', innerHTML: '' }),
  },
};
sandbox.window = sandbox;
vm.createContext(sandbox);
for (const f of ['icons-3d.js', 'icons-3d-more.js', 'icons-real.js']) vm.runInContext(web(f), sandbox, { filename: f });

const real = sandbox.PlcIconsReal;
if (!real) throw new Error('icons-real.js không khai báo PlcIconsReal');
const ids = real.ids().sort();

const q = (s) => '@"' + s.replace(/"/g, '""') + '"';   // chuỗi nguyên văn C#
const dict = (mode) => ids.map((id) => `        ["${id}"] = ${q(real.get(mode, id)())},`).join('\n');

const out = `// <auto-generated> Sinh bởi tools/solution-kit/gen-real-icons.js từ webapp/icons-real.js — đừng sửa tay. </auto-generated>
namespace GatewayApp.Ui;

/// <summary>Icon thiết bị THỰC TẾ dùng chung với webapp: SVG 48×48 ở dạng 3D (gradient, bóng) và phẳng (màu đặc). Vẽ bằng RealIcon.cs.</summary>
static class IconReal
{
    /// <summary>Bảng gradient (linearGradient/radialGradient) mà các SVG tham chiếu bằng url(#id).</summary>
    public const string Defs = ${q(defs.join(''))};

    public static readonly Dictionary<string, string> D3 = new()
    {
${dict('3d')}
    };

    public static readonly Dictionary<string, string> Flat = new()
    {
${dict('flat')}
    };
}
`;
const target = path.join(repo, 'tools', 'GatewayApp', 'Ui', 'IconReal.g.cs');
fs.writeFileSync(target, out.replace(/\r?\n/g, '\r\n'));
console.log(`đã ghi ${path.relative(repo, target)}: ${ids.length} icon × 2 dạng`);
